# Build a readable fixed-width text file. Tabular columns are aligned using spaces.
lines = [
    "VOCABOLARIO DI BASE – LINGUA VAMPIRICA",
    "Italiano = Vampiresco",
    "=" * 78,
    "",
    "NOTA:",
    "- Le forme sono proposte lessicali da verificare e approvare durante la costruzione dei dialoghi.",
    "- I verbi sono riportati all'infinito con il prefisso Ire-, come stabilito dalla grammatica.",
    "- Gli aggettivi sono forme base; gli avverbi si formano con il suffisso -ev.",
    "- I nomi sono riportati come radici lessicali: gli identificativi di classe (re, ke, se) si",
    "  aggiungono secondo le regole grammaticali già definite.",
    "- Le parole grammaticali già confermate (pronomi, preposizioni, congiunzioni, interrogativi,",
    "  negazione, particelle, numeri, ecc.) non vengono ripetute qui.",
    "- Le percentuali di lunghezza sillabica sono un obiettivo statistico del vocabolario, non un",
    "  vincolo rigido per ogni singola parola.",
    "",
    "ATTENZIONE ALLA REVISIONE:",
    "Questo è un primo repertorio ampio. Alcune forme potrebbero risultare troppo simili tra loro",
    "o collidere con vocaboli già fissati: durante la revisione, ogni voce va controllata prima",
    "di considerarla definitiva.",
    "",
]
for heading, entries in sections:
    lines.append(heading)
    lines.append("-" * len(heading))
    left_width = max(len(it) for it, _ in entries)
    for italian, vampirese in entries:
        lines.append(f"{italian:<{left_width}}  =  {vampirese}")
    lines.append("")

content = "\n".join(lines).rstrip() + "\n"
path = Path("vocabolario_base_vampiresco.txt")
path.write_text(content, encoding="utf-8")
print(f"Creato: {path}")
print(f"Voci: {sum(len(entries) for _, entries in sections)}")
print(f"Dimensione: {path.stat().st_size} byte")

